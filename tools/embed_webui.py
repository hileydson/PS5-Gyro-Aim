#!/usr/bin/env python3
"""Embed dependency-free companion and practice pages in the portable server."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
output = root / 'src/core/webui_page.c'
parts = ['/* Generated by tools/embed_webui.py; edit the HTML sources. */\n#include "webui.h"\n']
for filename, symbol in [('webui.html', 'GA_WEBUI_PAGE'), ('practice.html', 'GA_PRACTICE_PAGE')]:
    page = root / 'src/core' / filename
    parts.append('\nconst char ' + symbol + '[] =\n' + '\n'.join(
        json.dumps(line, ensure_ascii=False).replace("?", r"\?") for line in page.read_text().splitlines(keepends=True)) + ';\n')
output.write_text(''.join(parts))
